   subroutine cap_resolve(ctab, idx, cap, err)
      type(capnp_ptr_t), intent(in) :: ctab
      integer(int64), intent(in) :: idx
      type(rpc_cap_t), intent(out) :: cap
      integer, intent(out) :: err
      type(rpc_capnp_cap_descriptor_t) :: cd
      cap%kind = RPC_CAP_NONE
      cap%id = 0_int64
      err = CAPNP_OK
      if (idx < 0_int64 .or. idx >= capnp_list_len(ctab)) then
         err = CAPNP_ERR_BOUNDS
         return
      end if
      cd%p = capnp_list_get_struct(ctab, int(idx), err)
      if (err /= CAPNP_OK) return
      select case (rpc_capnp_cap_descriptor_which(cd))
      case (rpc_capnp_cap_descriptor_none_tag)
         cap%kind = RPC_CAP_NONE
      case (rpc_capnp_cap_descriptor_sender_hosted_tag)
         cap%kind = RPC_CAP_IMPORT
         cap%id = rpc_capnp_cap_descriptor_sender_hosted_get(cd)
      case (rpc_capnp_cap_descriptor_sender_promise_tag)
         cap%kind = RPC_CAP_IMPORT
         cap%id = rpc_capnp_cap_descriptor_sender_promise_get(cd)
      case (rpc_capnp_cap_descriptor_receiver_hosted_tag)
         cap%kind = RPC_CAP_IMPORT
         cap%id = rpc_capnp_cap_descriptor_receiver_hosted_get(cd)
      case default
         err = CAPNP_ERR_KIND
      end select
   end subroutine cap_resolve

   subroutine cap_resolve_id(ctab, idx, kind, id, err)
      type(capnp_ptr_t), intent(in) :: ctab
      integer(int64), intent(in) :: idx
      integer, intent(out) :: kind
      integer(int64), intent(out) :: id
      integer, intent(out) :: err
      type(rpc_capnp_cap_descriptor_t) :: cd
      kind = 0
      id = 0_int64
      err = CAPNP_OK
      if (idx < 0_int64 .or. idx >= capnp_list_len(ctab)) then
         err = CAPNP_ERR_BOUNDS
         return
      end if
      cd%p = capnp_list_get_struct(ctab, int(idx), err)
      if (err /= CAPNP_OK) return
      select case (rpc_capnp_cap_descriptor_which(cd))
      case (rpc_capnp_cap_descriptor_none_tag)
         kind = 0
      case (rpc_capnp_cap_descriptor_sender_hosted_tag)
         kind = 1
         id = rpc_capnp_cap_descriptor_sender_hosted_get(cd)
      case (rpc_capnp_cap_descriptor_sender_promise_tag)
         kind = 1
         id = rpc_capnp_cap_descriptor_sender_promise_get(cd)
      case (rpc_capnp_cap_descriptor_receiver_hosted_tag)
         kind = 1
         id = rpc_capnp_cap_descriptor_receiver_hosted_get(cd)
      case default
         err = CAPNP_ERR_KIND
      end select
   end subroutine cap_resolve_id

