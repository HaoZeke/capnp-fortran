   subroutine factory_dispatch(self, ctx, err)
      class(factory_server_t), intent(inout) :: self
      type(rpc_call_ctx_t), intent(inout) :: ctx
      integer, intent(out) :: err
      character(len=*), parameter :: ifname = 'schema/implicit.capnp:Factory'
      err = CAPNP_ERR_ARG
      if (ctx%interface_id /= FACTORY_INTERFACE_ID) then
         call rpc_ctx_unimplemented_interface(ctx, ifname, err)
         return
      end if
      select case (ctx%method_id)
      case (0)
         block
            type(factory_make_params_t) :: params
            type(factory_make_results_t) :: results
            params%p = ctx%params
            results%p = capnp_new_struct(ctx%rmsg, &
               FACTORY_MAKE_RESULTS_DWORDS, FACTORY_MAKE_RESULTS_PWORDS, err)
            if (err /= CAPNP_OK) return
            call self%make(ctx, params, results, err)
            if (err == CAPNP_OK) call payload_content_set(ctx%results, results%p, err)
         end block
      case (1)
         block
            type(factory_pair_params_t) :: params
            type(factory_pair_results_t) :: results
            params%p = ctx%params
            results%p = capnp_new_struct(ctx%rmsg, &
               FACTORY_PAIR_RESULTS_DWORDS, FACTORY_PAIR_RESULTS_PWORDS, err)
            if (err /= CAPNP_OK) return
            call self%pair(ctx, params, results, err)
            if (err == CAPNP_OK) call payload_content_set(ctx%results, results%p, err)
         end block
      case (2)
         block
            type(factory_boxy_params_t) :: params
            type(factory_boxy_results_t) :: results
            params%p = ctx%params
            results%p = capnp_new_struct(ctx%rmsg, &
               FACTORY_BOXY_RESULTS_DWORDS, FACTORY_BOXY_RESULTS_PWORDS, err)
            if (err /= CAPNP_OK) return
            call self%boxy(ctx, params, results, err)
            if (err == CAPNP_OK) call payload_content_set(ctx%results, results%p, err)
         end block
      case (3)
         block
            type(factory_talk_params_t) :: params
            type(factory_talk_results_t) :: results
            params%p = ctx%params
            results%p = capnp_new_struct(ctx%rmsg, &
               FACTORY_TALK_RESULTS_DWORDS, FACTORY_TALK_RESULTS_PWORDS, err)
            if (err /= CAPNP_OK) return
            call self%talk(ctx, params, results, err)
            if (err == CAPNP_OK) call payload_content_set(ctx%results, results%p, err)
         end block
      case (4)
         block
            type(factory_pick_params_t) :: params
            type(factory_pick_results_t) :: results
            params%p = ctx%params
            results%p = capnp_new_struct(ctx%rmsg, &
               FACTORY_PICK_RESULTS_DWORDS, FACTORY_PICK_RESULTS_PWORDS, err)
            if (err /= CAPNP_OK) return
            call self%pick(ctx, params, results, err)
            if (err == CAPNP_OK) call payload_content_set(ctx%results, results%p, err)
         end block
      case default
         call rpc_ctx_unimplemented_method(ctx, ifname, &
            FACTORY_INTERFACE_ID, err)
      end select
   end subroutine factory_dispatch

