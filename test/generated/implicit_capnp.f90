   subroutine holder_dispatch(self, ctx, err)
      class(holder_server_t), intent(inout) :: self
      type(rpc_call_ctx_t), intent(inout) :: ctx
      integer, intent(out) :: err
      character(len=*), parameter :: ifname = 'schema/implicit.capnp:Holder'
      err = CAPNP_ERR_ARG
      if (ctx%interface_id /= HOLDER_INTERFACE_ID) then
         call rpc_ctx_unimplemented_interface(ctx, ifname, err)
         return
      end if
      select case (ctx%method_id)
      case (0)
         block
            type(holder_put_params_t) :: params
            type(holder_put_results_t) :: results
            params%p = ctx%params
            results%p = capnp_new_struct(ctx%rmsg, &
               HOLDER_PUT_RESULTS_DWORDS, HOLDER_PUT_RESULTS_PWORDS, err)
            if (err /= CAPNP_OK) return
            call self%put(ctx, params, results, err)
            if (err == CAPNP_OK) call payload_content_set(ctx%results, results%p, err)
         end block
      case default
         call rpc_ctx_unimplemented_method(ctx, ifname, &
            HOLDER_INTERFACE_ID, err)
      end select
   end subroutine holder_dispatch

