      type(capnp_ptr_t) :: q
      integer :: err
      q = capnp_getp(h%p, 0, err)
      v = err == CAPNP_OK .and. q%kind /= CAPNP_PK_NULL
   end function hold_data_body_has

   function hold_data_body_get(h, err) result(o)
      type(hold_data_t), intent(in) :: h
      integer, intent(out) :: err
      type(seed_t) :: o
      type(capnp_message_t), save, target :: defmsg
      logical, save :: defloaded = .false.
      type(capnp_ptr_t) :: d
      o%p = capnp_getp(h%p, 0, err)
      if (err /= CAPNP_OK .or. o%p%kind /= CAPNP_PK_NULL) return
      if (.not. defloaded) then
         call capnp_deserialize_bytes(HOLD_DATA_BODY_DEFAULT, defmsg, err)
         if (err /= CAPNP_OK) return
         defloaded = .true.
      end if
      d = capnp_root(defmsg, err)
      if (err /= CAPNP_OK) return
      if (associated(h%p%msg)) then
         if (h%p%msg%is_builder) then
            ! Builder get() materialises the default in place, as C++ does.
            o%p = capnp_copy(h%p%msg, d, err)
            if (err == CAPNP_OK) call capnp_setp(h%p, 0, o%p, err)
            return
         end if
      end if
      o%p = d
   end function hold_data_body_get

   function hold_data_body_init(h, err) result(o)
      type(hold_data_t), intent(in) :: h
      integer, intent(out) :: err
      type(seed_t) :: o
      o%p = capnp_new_struct(h%p%msg, SEED_DWORDS, SEED_PWORDS, err)
      if (err == CAPNP_OK) call capnp_setp(h%p, 0, o%p, err)
   end function hold_data_body_init

   subroutine hold_data_body_set(h, src, err)
      type(hold_data_t), intent(in) :: h
      type(seed_t), intent(in) :: src
      integer, intent(out) :: err
      type(capnp_ptr_t) :: c
      c = capnp_copy(h%p%msg, src%p, err)
      if (err == CAPNP_OK) call capnp_setp(h%p, 0, c, err)
   end subroutine hold_data_body_set

   subroutine cap_resolve(ctab, idx, cap, err)
      type(capnp_ptr_t), intent(in) :: ctab
      integer(int64), intent(in) :: idx
      type(rpc_cap_t), intent(out) :: cap
      integer, intent(out) :: err
      type(rpc_capnp_cap_descriptor_t) :: cd
      cap%kind = RPC_CAP_NONE
      cap%id = 0_int64
      err = CAPNP_OK
      if (idx < 0_int64 .or. idx >= capnp_list_len(ctab)) then
         err = CAPNP_ERR_BOUNDS
         return
      end if
      cd%p = capnp_list_get_struct(ctab, int(idx), err)
      if (err /= CAPNP_OK) return
      select case (rpc_capnp_cap_descriptor_which(cd))
      case (rpc_capnp_cap_descriptor_none_tag)
         cap%kind = RPC_CAP_NONE
      case (rpc_capnp_cap_descriptor_sender_hosted_tag)
         cap%kind = RPC_CAP_IMPORT
         cap%id = rpc_capnp_cap_descriptor_sender_hosted_get(cd)
      case (rpc_capnp_cap_descriptor_sender_promise_tag)
         cap%kind = RPC_CAP_IMPORT
         cap%id = rpc_capnp_cap_descriptor_sender_promise_get(cd)
      case (rpc_capnp_cap_descriptor_receiver_hosted_tag)
         cap%kind = RPC_CAP_IMPORT
         cap%id = rpc_capnp_cap_descriptor_receiver_hosted_get(cd)
      case default
         err = CAPNP_ERR_KIND
      end select
   end subroutine cap_resolve

